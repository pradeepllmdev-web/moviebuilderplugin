def _measured():
 import json,os
 p=os.path.join(os.path.dirname(os.path.abspath(__file__)),'scenes','ship_assets','gait_report.json')
 try:return {k:v['planted'] for k,v in json.load(open(p)).items() if v.get('planted',0)>0}
 except (OSError,ValueError):return {}
MEASURED=_measured()
def natural_speed(name):
 g=GAITS[name]
 if g['kind']=='clip':return g['speed']
 if name in MEASURED:return MEASURED[name]
 return 2*g['amp']/(g['stance']*g['cycle']/FPS)
def play_scale(name,speed,size=1.):
 """NLA strip scale (>1 slower) that makes a character of height factor `size` cover `speed` m/s with a planted foot; the natural speed grows with the size"""
 return natural_speed(name)*size/max(1e-6,speed)
def cycle_seconds(name,scale=1.):return GAITS[name]['cycle']/FPS*scale
def for_personality(posture,mood=None):
 """gait name for a personality: posture word from the cast registry"""
 return POSTURE_GAIT.get(posture,'walk')
POSTURE_GAIT={'neutral':'walk','proud':'strut','tired':'shuffle','jaunty':'bounce','tense':'sneak','angry':'stomp','hurried':'brisk','hunched':'shuffle'}
