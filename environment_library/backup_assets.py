"""Back up everything the project needs that git does not hold (git ignores *.blend, downloads and voice models).

    python backup_assets.py <destination folder>            copy into <destination>/assets_backup_<date>/ (default: a folder beside the repository)
    python backup_assets.py <destination> --dry-run         only list what would be copied and its size
    python backup_assets.py <destination> --no-voices       skip the Piper voice models (about 1.1 GB, downloadable again)
    python backup_assets.py --restore <backup folder>       copy a backup back into place

What is saved (paths relative to environment_library):
  scenes/ship_assets/        the lion rig and every lion clip (leo_*.blend, routes, gait report): every lion film needs them
  assets/quaternius_*_download/   the animal and dinosaur models and their animations (farm_egg)
  assets/ual*_download/      the Universal Animation Library downloads (the people library itself is in git)
  voices/                    Piper voice models (*.onnx) and the cached lines (voices/cache), so voices stay identical
Everything else (code, films, tests, the humanoid library) is in git; rebuilt scenes and renders are regenerated by perf_movie.py and render_film.py."""
import datetime,shutil,sys
from pathlib import Path
H=Path(__file__).resolve().parent
ITEMS=['scenes/ship_assets','assets/quaternius_farm_animals_download','assets/quaternius_dinosaurs_download','assets/ual1_download','assets/ual2_download','voices']
def size(p):
 p=Path(p)
 return p.stat().st_size if p.is_file() else sum(f.stat().st_size for f in p.rglob('*') if f.is_file())
def plan(no_voices=False):
 return [(i,H/i) for i in ITEMS if (H/i).exists() and not (no_voices and i=='voices')]
def copy(dest,no_voices=False,dry=False):
 dest=Path(dest)/('assets_backup_%s'%datetime.date.today().isoformat());total=0
 for rel,src in plan(no_voices):
  n=size(src);total+=n;print('%8.0f MB  %s'%(n/1e6,rel))
  if not dry:shutil.copytree(src,dest/rel,dirs_exist_ok=True,ignore=shutil.ignore_patterns('*.blend1','*.tmp','__pycache__'))
 print('total %.1f GB %s'%(total/1e9,'(dry run, nothing copied)' if dry else '-> '+str(dest)));return dest
def restore(backup):
 backup=Path(backup)
 for rel in ITEMS:
  if (backup/rel).exists():shutil.copytree(backup/rel,H/rel,dirs_exist_ok=True);print('restored',rel)
if __name__=='__main__':
 a=sys.argv[1:]
 if not a:print(__doc__);sys.exit(1)
 if a[0]=='--restore':restore(a[1])
 else:copy(a[0],'--no-voices' in a,'--dry-run' in a)
